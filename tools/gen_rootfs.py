import os

ROOTFS_DIR = "sys/rootfs"
OUTPUT_FILE = "sys/kernel/rootfs_data.h"

def main():
    if not os.path.exists(ROOTFS_DIR):
        print(f"Error: {ROOTFS_DIR} not found")
        return

    files_data = []
    
    for root, dirs, files in os.walk(ROOTFS_DIR):
        for file in files:
            full_path = os.path.join(root, file)
            rel_path = "/" + os.path.relpath(full_path, ROOTFS_DIR).replace("\\", "/")
            
            with open(full_path, "rb") as f:
                data = f.read()
            
            hex_array = ", ".join(f"0x{b:02X}" for b in data)
            files_data.append((rel_path, hex_array, len(data)))

    with open(OUTPUT_FILE, "w") as out:
        out.write("/* AUTO-GENERATED BY tools/gen_rootfs.py. DO NOT EDIT. */\n")
        out.write("#ifndef ROOTFS_DATA_H\n#define ROOTFS_DATA_H\n\n")
        out.write("typedef struct { const char* path; const unsigned char* data; unsigned int size; } rootfs_file_t;\n\n")
        
        for i, (path, hex_array, size) in enumerate(files_data):
            out.write(f"static const unsigned char rootfs_data_{i}[] = {{ {hex_array} }};\n")
            
        out.write("\nstatic const rootfs_file_t rootfs_files[] = {\n")
        for i, (path, hex_array, size) in enumerate(files_data):
            out.write(f'    {{ "{path}", rootfs_data_{i}, {size} }},\n')
        out.write("};\n\n")
        out.write(f"#define ROOTFS_FILE_COUNT {len(files_data)}\n\n")
        out.write("#endif\n")

    print(f"Generated {OUTPUT_FILE} with {len(files_data)} files.")

if __name__ == "__main__":
    main()