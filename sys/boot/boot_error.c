#define LOGO_WIDTH  64
#define LOGO_HEIGHT 64

static uint32_t* fb_addr = 0;
static uint32_t fb_width = 0;
static uint32_t fb_height = 0;
static uint32_t fb_pitch = 0;
static int fb_bpp = 0;

extern uint32_t multiboot_info_ptr;

static void fb_init(void) {
    if (!multiboot_info_ptr) return;
    uint8_t* ptr = (uint8_t*)(uintptr_t)multiboot_info_ptr;
    uint32_t total_size = *(uint32_t*)ptr;
    uint8_t* tag = ptr + 8;
    while (tag < ptr + total_size) {
        uint32_t type = *(uint32_t*)tag;
        uint32_t size = *(uint32_t*)(tag + 4);
        if (type == 0) break;
        if (type == 8) {
            fb_addr   = (uint32_t*)(uintptr_t)(*(uint64_t*)(tag + 8));
            fb_pitch  = *(uint32_t*)(tag + 16);
            fb_width  = *(uint32_t*)(tag + 20);
            fb_height = *(uint32_t*)(tag + 24);
            fb_bpp    = *(uint8_t*)(tag + 28);
            break;
        }
        tag += (size + 7) & ~7;
    }
}

static void putpixel(int x, int y, uint32_t color) {
    if (x < 0 || y < 0 || x >= (int)fb_width || y >= (int)fb_height) return;
    uint32_t* pixel = (uint32_t*)((uint8_t*)fb_addr + y * fb_pitch + x * 4);
    *pixel = color;
}

static void fb_draw_image(int x, int y, const uint16_t* data, int w, int h) {
    for (int j = 0; j < h; j++) {
        for (int i = 0; i < w; i++) {
            uint16_t rgb565 = data[j * w + i];
            uint8_t r = (rgb565 >> 11) & 0x1F;
            uint8_t g = (rgb565 >> 5)  & 0x3F;
            uint8_t b =  rgb565        & 0x1F;
            uint32_t color = (((r * 255) / 31) << 16) | (((g * 255) / 63) << 8) | ((b * 255) / 31);
            putpixel(x + i, y + j, color);
        }
    }
}

void kernel_main(void) {
    fb_init();
    
    // Заливаем фон темно-синим (как BSOD)
    if (fb_bpp == 32) {
        for (int y = 0; y < (int)fb_height; y++)
            for (int x = 0; x < (int)fb_width; x++)
                putpixel(x, y, 0x000000AA);
                
        // Рисуем логотип по центру
        int lx = (fb_width - LOGO_WIDTH) / 2;
        int ly = (fb_height - LOGO_HEIGHT) / 2 - 50;
        fb_draw_image(lx, ly, LogoNwOS, LOGO_WIDTH, LOGO_HEIGHT);
    }

    // Выведем текст прямо через VGA (на случай если фреймбуфер не сработал)
    volatile uint16_t* video = (volatile uint16_t*)0xB8000;
    const char* msg = " FATAL: NwOS Kernel could not be loaded! Check build logs. ";
    for (int i = 0; msg[i]; i++) {
        video[22 * 80 + 10 + i] = (uint16_t)msg[i] | (0x4F << 8); // Белый на красном
    }
    const char* msg2 = " Press Ctrl+Alt+Del to restart. ";
    for (int i = 0; msg2[i]; i++) {
        video[23 * 80 + 23 + i] = (uint16_t)msg2[i] | (0x4F << 8);
    }

    while (1) {
        __asm__ volatile ("hlt");
    }
}